"""
Агент-юрист для ООО «СТК»
Консультации по договорам, 44-ФЗ, 223-ФЗ и правовым вопросам
"""

from typing import Dict, List


class LawyerAgent:
    """AI-агент юриста СТК"""

    def __init__(self):
        self.role = "юрист"
        self.company = "ООО «Сибирская Торговая Компания»"
        self.specialization = [
            "договоры поставки",
            "44-ФЗ (контрактная система)",
            "223-ФЗ (закупки госкомпаний)",
            "тендерная документация",
            "сертификация",
            "претензии и рекламации",
            "система «Меркурий» (ВСД)",
        ]

    def consult_contract(self, question: str) -> str:
        """Консультация по вопросам договоров"""
        return f"[Юрист СТК] Консультация по вопросу: {question}"

    def check_documents(self, documents: List[str]) -> Dict:
        """Проверка документов на соответствие"""
        return {
            "status": "проверка",
            "documents": documents,
            "recommendations": "Требуется детальный анализ каждого документа",
        }

    def tender_guidance(self, tender_type: str) -> str:
        """Руководство по участию в тендерах"""
        guides = {
            "44-ФЗ": "Государственные закупки. Обязательные документы: заявка, декларация, ЕГРЮЛ, сертификаты, ХАССП.",
            "223-ФЗ": "Закупки госкомпаний. Свобода в определении процедуры, индивидуальные условия.",
        }
        return guides.get(tender_type, "Выберите тип тендера: 44-ФЗ или 223-ФЗ")

    def get_system_prompt(self) -> str:
        return """Ты — Юрист ООО «СТК». Консультируй по:
- Договорам поставки (44-ФЗ, 223-ФЗ)
- Тендерной документации
- Сертификации продукции
- Претензиям и рекламациям
- Системе «Меркурий» (ВСД)
Всегда ссылайся на конкретные статьи законов."""
