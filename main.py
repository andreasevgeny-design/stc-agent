    def detect_role(self, message: str) -> EmployeeRole:
        """Определение роли сотрудника по содержанию запроса"""
        message_lower = message.lower()
        scores = {}

        for role, keywords in self.ROLE_KEYWORDS.items():
            score = sum(1 for kw in keywords if kw in message_lower)
            if score > 0:
                scores[role] = score

        if not scores:
            return EmployeeRole.SALES_MANAGER

        max_score = max(scores.values())
        top_roles = [r for r, s in scores.items() if s == max_score]

        if len(top_roles) == 1:
            return top_roles[0]

        # Приоритет при совпадении: специализированные роли важнее менеджера продаж
        priority = [
            EmployeeRole.MARKETER,
            EmployeeRole.DIRECTOR,
            EmployeeRole.LAWYER,
            EmployeeRole.ACCOUNTANT,
            EmployeeRole.SALES_MANAGER,
        ]
        for role in priority:
            if role in top_roles:
                return role

        return max(scores, key=scores.get)

